#!/usr/bin/env python3
"""
RFC 9449 DPoP proof generation and verification (Python Architectural Simulation).

KEY CUSTODY: SIMULATION_ONLY. Keys are exportable software ECDSA P-256 keys generated by
`cryptography`, NOT Apple Secure Enclave keys. CORE-V1 Invariant 4 (keys in SEP) is not met
by this module; the v3.0 target binds DPoP keys to the SEP (FS-703).

Verification (remediates F-007 — the proxy previously never inspected DPoP at all):
  * compact JWS with exactly three parts; header typ == "dpop+jwt", alg == "ES256", public
    EC P-256 `jwk` with no private members
  * ES256 signature over the JWS signing input, using the raw 64-byte R||S encoding (RFC 7518)
  * `htm` equals the request method; `htu` equals the request URI (scheme/host/port/path,
    query and fragment ignored per RFC 9449 §4.3)
  * `iat` within ±`max_skew_s`; `jti` unseen within the replay window (bounded TTL cache)
  * optional `nonce` match; optional JWK SHA-256 thumbprint (RFC 7638) binding to `expected_jkt`
"""

from __future__ import annotations

import base64
import hashlib
import json
import threading
import time
import uuid
from collections import OrderedDict
from typing import Any, Dict, Optional
from urllib.parse import urlsplit, urlunsplit

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature,
    encode_dss_signature,
)

KEY_CUSTODY = "SIMULATION_ONLY_SOFTWARE_KEY"


def b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode("ascii").rstrip("=")


def b64u_decode(text: str) -> bytes:
    if not isinstance(text, str) or any(c in text for c in "+/="):
        raise ValueError("invalid base64url")
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def jwk_thumbprint(jwk: Dict[str, str]) -> str:
    canon = json.dumps(
        {"crv": jwk["crv"], "kty": jwk["kty"], "x": jwk["x"], "y": jwk["y"]},
        separators=(",", ":"),
        sort_keys=True,
    )
    return b64u(hashlib.sha256(canon.encode()).digest())


def normalize_htu(uri: str) -> str:
    parts = urlsplit(uri)
    return urlunsplit(
        (parts.scheme.lower(), parts.netloc.lower(), parts.path or "/", "", "")
    )


class DPoPProofGenerator:
    """Creates DPoP proofs with an ephemeral SIMULATION_ONLY software key."""

    key_custody = KEY_CUSTODY

    def __init__(self, private_key: Optional[ec.EllipticCurvePrivateKey] = None):
        self.private_key = private_key or ec.generate_private_key(ec.SECP256R1())
        self.public_key = self.private_key.public_key()

    def export_jwk(self) -> Dict[str, str]:
        nums = self.public_key.public_numbers()
        return {
            "kty": "EC",
            "crv": "P-256",
            "x": b64u(nums.x.to_bytes(32, "big")),
            "y": b64u(nums.y.to_bytes(32, "big")),
        }

    def thumbprint(self) -> str:
        return jwk_thumbprint(self.export_jwk())

    def create_proof(
        self,
        http_method: str,
        http_uri: str,
        nonce: Optional[str] = None,
        iat: Optional[int] = None,
        jti: Optional[str] = None,
    ) -> str:
        header = {"typ": "dpop+jwt", "alg": "ES256", "jwk": self.export_jwk()}
        payload: Dict[str, Any] = {
            "jti": jti or str(uuid.uuid4()),
            "htm": http_method.upper(),
            "htu": http_uri,
            "iat": int(time.time()) if iat is None else iat,
        }
        if nonce:
            payload["nonce"] = nonce
        h = b64u(json.dumps(header, separators=(",", ":")).encode())
        p = b64u(json.dumps(payload, separators=(",", ":")).encode())
        der = self.private_key.sign(f"{h}.{p}".encode(), ec.ECDSA(hashes.SHA256()))
        r, s = decode_dss_signature(der)
        return f"{h}.{p}.{b64u(r.to_bytes(32, 'big') + s.to_bytes(32, 'big'))}"


class DPoPVerificationError(Exception):
    pass


class DPoPVerifier:
    def __init__(
        self, max_skew_s: int = 60, replay_window_s: int = 300, max_cache: int = 100_000
    ):
        self.max_skew_s = max_skew_s
        self.replay_window_s = replay_window_s
        self.max_cache = max_cache
        self._seen: "OrderedDict[str, float]" = OrderedDict()
        self._lock = threading.Lock()

    def _remember_jti(self, jti: str, now: float) -> None:
        with self._lock:
            while self._seen:  # drop only EXPIRED entries; never evict a live jti
                k, exp = next(iter(self._seen.items()))
                if exp > now:
                    break
                self._seen.popitem(last=False)
            if jti in self._seen:
                raise DPoPVerificationError("jti replay detected")
            if len(self._seen) >= self.max_cache:
                # Fail closed: evicting a live jti would re-open a replay window.
                raise DPoPVerificationError(
                    "jti replay cache saturated; rejecting until entries expire"
                )
            self._seen[jti] = now + self.replay_window_s

    def verify(
        self,
        proof: str,
        htm: str,
        htu: str,
        nonce: Optional[str] = None,
        expected_jkt: Optional[str] = None,
        now: Optional[float] = None,
    ) -> Dict[str, Any]:
        now = time.time() if now is None else now
        if not isinstance(proof, str) or proof.count(".") != 2:
            raise DPoPVerificationError("malformed DPoP proof")
        h_b64, p_b64, s_b64 = proof.split(".")
        try:
            header = json.loads(b64u_decode(h_b64))
            claims = json.loads(b64u_decode(p_b64))
            sig = b64u_decode(s_b64)
        except Exception as exc:
            raise DPoPVerificationError(f"undecodable DPoP proof: {exc}") from exc
        if header.get("typ") != "dpop+jwt":
            raise DPoPVerificationError("typ must be dpop+jwt")
        if header.get("alg") != "ES256":
            raise DPoPVerificationError("alg must be ES256")
        jwk = header.get("jwk") or {}
        if jwk.get("kty") != "EC" or jwk.get("crv") != "P-256" or "d" in jwk:
            raise DPoPVerificationError("jwk must be a public EC P-256 key")
        try:
            pub = ec.EllipticCurvePublicNumbers(
                int.from_bytes(b64u_decode(jwk["x"]), "big"),
                int.from_bytes(b64u_decode(jwk["y"]), "big"),
                ec.SECP256R1(),
            ).public_key()
        except Exception as exc:
            raise DPoPVerificationError(f"invalid jwk: {exc}") from exc
        if len(sig) != 64:
            raise DPoPVerificationError("ES256 signature must be 64 bytes (R||S)")
        der = encode_dss_signature(
            int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big")
        )
        try:
            pub.verify(der, f"{h_b64}.{p_b64}".encode(), ec.ECDSA(hashes.SHA256()))
        except InvalidSignature as exc:
            raise DPoPVerificationError("signature verification failed") from exc
        if claims.get("htm") != htm.upper():
            raise DPoPVerificationError("htm mismatch")
        if normalize_htu(str(claims.get("htu", ""))) != normalize_htu(htu):
            raise DPoPVerificationError("htu mismatch")
        iat = claims.get("iat")
        if not isinstance(iat, int) or abs(now - iat) > self.max_skew_s:
            raise DPoPVerificationError("iat outside allowed clock skew")
        if nonce is not None and claims.get("nonce") != nonce:
            raise DPoPVerificationError("nonce mismatch")
        jkt = jwk_thumbprint(jwk)
        if expected_jkt is not None and jkt != expected_jkt:
            raise DPoPVerificationError("proof key does not match bound jkt (cnf)")
        jti = claims.get("jti")
        if not isinstance(jti, str) or not 16 <= len(jti) <= 128:
            raise DPoPVerificationError("jti missing or malformed")
        self._remember_jti(jti, now)
        return {"jkt": jkt, "jti": jti, "iat": iat}
