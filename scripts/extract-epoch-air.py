#!/usr/bin/env python3
"""Translate every actual exported EpochAir polynomial into executable Lean.

Default is a read-only correspondence check. --write is an explicit source
regeneration operation, followed by review and kernel recompilation.
Unknown operators/layouts fail closed; no constraint is filtered or replaced.
"""

import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "proofs/lean4/Enclave/EpochAirExtracted.lean"


def expression(node):
    op, *args = node
    if op == "constant" and len(args) == 1:
        return str(args[0])
    if op == "main" and len(args) == 2 and args[0] in (0, 1):
        return f"(e.main {args[0]} {args[1]})"
    if op == "public" and len(args) == 1:
        return f"(e.public {args[0]})"
    if op in ("first", "last", "transition") and not args:
        return "e." + op
    if op in ("add", "sub", "mul") and len(args) == 2:
        symbol = dict(add="+", sub="-", mul="*")[op]
        return f"({expression(args[0])} {symbol} {expression(args[1])})"
    if op == "neg" and len(args) == 1:
        return f"(-{expression(args[0])})"
    raise ValueError(f"unsupported AIR expression: {node!r}")


def render(export):
    air = export["EpochAir"]
    if export["prime"] != 2130706433 or air["width"] != 52 or air["public_count"] != 57:
        raise ValueError("unexpected field/layout: review new AIR before regeneration")
    expected = dict(
        active=0,
        bits=14,
        cap_public=1,
        delta=4,
        delta_bits=20,
        fold=2,
        slack=6,
        used=5,
        used_bits=34,
    )
    if air["columns"] != expected or len(air["constraints"]) != 62:
        raise ValueError("unexpected columns/constraint count")
    lines = [
        "import Enclave.FieldRangeProofs",
        "",
        "/-! GENERATED by scripts/extract-epoch-air.py from the actual Rust",
        "EpochAir::eval symbolic polynomials. Do not edit or assume any are absent. -/",
        "namespace Enclave.EpochAirExtracted",
        "",
        "abbrev F := Enclave.FieldRangeProofs.F",
        "",
        "structure Env where",
        "  main : Nat → Nat → F",
        "  public : Nat → F",
        "  first : F",
        "  last : F",
        "  transition : F",
        "",
    ]
    for i, constraint in enumerate(air["constraints"]):
        lines.append(f"def c{i} (e : Env) : F := {expression(constraint)}")
    lines += ["", "def constraint (e : Env) (i : Fin 62) : F :=", "  match i.val with"]
    lines += [f"  | {i} => c{i} e" for i in range(61)]
    lines += [
        "  | _ => c61 e",
        "",
        "def satisfies (e : Env) : Prop := ∀ i, constraint e i = 0",
        "",
        "end Enclave.EpochAirExtracted",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    actual = subprocess.check_output(
        [
            "cargo",
            "run",
            "--locked",
            "-q",
            "-p",
            "enclave-zk-auditor",
            "--example",
            "audit-constraints",
        ],
        cwd=ROOT,
        text=True,
    )
    expected = render(json.loads(actual))
    if args.write:
        OUT.write_text(expected)
        print("WROTE: all 62 actual EpochAir polynomials; review and compile proofs")
    elif not OUT.exists() or OUT.read_text() != expected:
        raise SystemExit(
            "FAIL: Lean polynomials differ from actual production EpochAir"
        )
    else:
        print(
            "PASS: all 62 Lean field polynomials match actual exported EpochAir constraints"
        )


if __name__ == "__main__":
    main()
