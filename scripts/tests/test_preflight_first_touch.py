    def test_closed_schema_and_duplicate_fields(self):
        value = target()
        P.validate_target(value)
        for key in ("broker", "shared_read_only_inputs", "authority_config"):
            bad = copy.deepcopy(value)
            del bad[key]
            with self.assertRaises(P.Refusal):
                P.validate_target(bad)
        for mutate in (
            lambda v: v.update(extra=True),
            lambda v: v["layout"].update(extra=True),
            lambda v: v.update(version=True),
            lambda v: v.update(profile="L1"),
        ):
            bad = copy.deepcopy(value)
            mutate(bad)
            with self.assertRaises(P.Refusal):
                P.validate_target(bad)
        with self.assertRaisesRegex(P.Refusal, "DUPLICATE_JSON_FIELD"):
            P.strict_json(b'{"v":1,"v":1}')

