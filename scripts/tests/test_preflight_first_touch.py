    def test_socket_metadata_never_implies_health_and_rejects_symlink_or_wrong_owner(
        self,
    ):
        def correct(path):
            return (
                metadata(702, 8712, stat.S_IFSOCK | 0o660)
                if path.endswith(".sock")
                else metadata()
            )

        self.assertEqual(
            P.socket_observation("/run/test/cas.sock", 702,
                                 8712, correct)["status"],
            "OBSERVED_SOCKET_METADATA_ONLY",
        )
        self.assertEqual(
            P.socket_observation("/run/test/cas.sock", 703,
                                 8712, correct)["status"],
            "FAIL_SOCKET_METADATA",
        )

        def symlink(path):
            return (
                metadata(mode=stat.S_IFLNK | 0o777)
                if path == "/run/test"
                else correct(path)
            )

        self.assertEqual(
            P.socket_observation("/run/test/cas.sock", 702,
                                 8712, symlink)["status"],
            "FAIL_SOCKET_METADATA",
        )
        self.assertEqual(
            P.socket_observation(None, None, 8703)[
                "status"], "UNKNOWN_CONSOLE_SESSION"
        )

    def installed_fixture(self, entry, source):
        # Only relocate immutable Rust-produced bytes. Do not generate expected
        # inputs from the checker's installed_plist_specs implementation.
        files = {}
        for path, content in source.items():
            if path.startswith(entry["plists"] + "/") and path.endswith(".plist"):
                name = path.rsplit("/", 1)[1]
                suffix = name.removeprefix(
                    entry["target"]["layout"]["launchd_namespace"] + "."
                ).removesuffix(".plist")
                directory = (
                    "LaunchAgents"
                    if suffix in ("intent", "oidc-broker")
                    else "LaunchDaemons"
                )
                files["/Library/" + directory + "/" + name] = content
        calls = []

        def observer(path, maximum):
            calls.append(path)
            raw = files.get(path)
            if raw is not None:
                self.assertLessEqual(len(raw), maximum)
            return raw, {
                "status": (
                    "OBSERVED_PROTECTED_INSTALLED_FILE"
                    if raw is not None
                    else "UNKNOWN_INSTALLED_JOB_ABSENT"
                ),
                "metadata": [{"fixture_only": True, "path": path}],
            }

        return files, calls, observer

