    @unittest.skipUnless(hasattr(os, "fork"), "UNEXERCISED: Unix fork unavailable")
    def test_exited_leader_does_not_leave_pipe_holding_descendant_running(self):
        with tempfile.TemporaryDirectory(prefix="first-touch-command-") as tmp:
            pidfile = Path(tmp) / "descendant.pid"
            code = (
                "import os,time\nchild=os.fork()\nif child:\n"
                f" open({str(pidfile)!r},'w').write(str(child))\n os._exit(0)\n"
                "time.sleep(30)\n"
            )
            with self.assertRaisesRegex(P.Refusal, "COMMAND_TIMEOUT"):
                P.bounded_command([sys.executable, "-c", code], timeout=0.5)
            child = int(pidfile.read_text())
            deadline = time.monotonic() + 1.0
            running = True
            while time.monotonic() < deadline:
                try:
                    os.kill(child, 0)
                except ProcessLookupError:
                    running = False
                    break
                # Linux may retain an orphan zombie briefly. It is terminated,
                # cannot run, and cannot retain pipes; do not claim reaping.
                proc = Path(f"/proc/{child}/stat")
                try:
                    if proc.read_text().split(")", 1)[1].split()[0] == "Z":
                        running = False
                        break
                except FileNotFoundError:
                    pass
                time.sleep(0.01)
            self.assertFalse(
                running, "isolated descendant survived completed timeout cleanup"
            )

    def test_held_reader_subtree_rejects_modes_links_caps_and_mutation(self):
        # This deliberately tests the shared held-directory walker from a private
        # FD. It does not claim the /tmp ancestor is protected or distinct UID
        # chown applied on a workspace filesystem.
        if os.geteuid() != 0:
            self.skipTest(
                "UNEXERCISED: held root-owner subtree fixture requires actual root"
            )
        with tempfile.TemporaryDirectory(prefix="first-touch-reader-") as tmp:
            root = Path(tmp)
            root.chmod(0o700)
            public = root / "public.json"
            public.write_bytes(b"{}")
            public.chmod(0o600)
            fd = os.open(tmp, os.O_RDONLY | os.O_DIRECTORY)
            try:
                self.assertEqual(P._read_at(fd, ["public.json"], 4), b"{}")
                public.chmod(0o620)
                with self.assertRaises(P.Refusal):
                    P._read_at(fd, ["public.json"], 4)
                public.chmod(0o600)
                with self.assertRaises(P.Refusal):
                    P._read_at(fd, ["public.json"], 1)
                (root / "symlink").symlink_to(public)
                with self.assertRaises(OSError):
                    P._read_at(fd, ["symlink"], 4)
                os.link(public, root / "hardlink")
                with self.assertRaises(P.Refusal):
                    P._read_at(fd, ["public.json"], 4)
                (root / "hardlink").unlink()
                original = P.os.read

                def mutate(number, maximum):
                    data = original(number, maximum)
                    public.write_bytes(b"changed")
                    return data

                with mock.patch.object(P.os, "read", side_effect=mutate):
                    with self.assertRaises(P.Refusal):
                        P._read_at(fd, ["public.json"], 32)
            finally:
                os.close(fd)

