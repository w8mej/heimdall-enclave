def target(name="dedicated", role="dedicated-test"):
    root = "/first-touch-fixtures/" + name
    layout = {
        key: root + "/" + key.replace("_root", "").replace("_dir", "")
        for key in P.ROOT_FIELDS
    }
    layout["custody_bundle"] = layout["support_root"] + "/Custody.app"
    layout.update(
        launchd_namespace="com.depot." + name,
        mach_service="com.depot." + name + ".exception",
    )
    return dict(
        version=1,
        target_id=name,
        role=role,
        profile="L2",
        authority_config=root + "/support/authority.json",
        expected_artifacts_manifest=root + "/support/artifacts.json",
        codesign_pins_file=root + "/support/pins.json",
        signing_identity_mode="local-pins",
        layout=layout,
        broker=None,
        shared_read_only_inputs=[],
    )


def metadata(uid=0, gid=0, mode=stat.S_IFDIR | 0o755):
    return SimpleNamespace(st_uid=uid, st_gid=gid, st_mode=mode, st_dev=1, st_ino=2)


